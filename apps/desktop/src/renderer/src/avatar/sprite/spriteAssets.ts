import {
  type LayeredSpriteManifest,
  parseSpriteManifest,
  type SpriteLayerName,
  type StaticSpriteManifest,
} from './manifest'

export type SpriteLayers = Record<SpriteLayerName, Record<string, string>>

export type SpriteAssets =
  | { manifest: StaticSpriteManifest; baseUrl: string }
  | { manifest: LayeredSpriteManifest; baseUrl: string; layers: SpriteLayers }

/** Module path (e.g. "./assets/akari/manifest.json") -> parsed JSON / asset URL. */
export type ModuleMap<T> = Record<string, T>

/**
 * Builds every valid sprite set from the bundled assets, keyed by id (= character id).
 * Sets with an invalid manifest or a missing image are skipped, so that character
 * falls back to the placeholder avatar.
 */
export function buildSpriteSets(
  manifests: ModuleMap<unknown>,
  images: ModuleMap<string>,
): Map<string, SpriteAssets> {
  const sets = new Map<string, SpriteAssets>()
  for (const [path, data] of Object.entries(manifests)) {
    const manifest = parseSpriteManifest(data)
    if (!manifest) continue
    const assets = resolveImages(path.replace(/manifest\.json$/, ''), manifest, images)
    if (assets) sets.set(manifest.id, assets)
  }
  return sets
}

function resolveImages(
  dir: string,
  manifest: StaticSpriteManifest | LayeredSpriteManifest,
  images: ModuleMap<string>,
): SpriteAssets | null {
  const baseUrl = images[`${dir}${manifest.base}`]
  if (!baseUrl) return null
  if (manifest.kind === 'static') return { manifest, baseUrl }

  const layers: SpriteLayers = { eyes: {}, mouth: {} }
  for (const layer of ['eyes', 'mouth'] as const) {
    for (const source of manifest.sources) {
      const url = images[`${dir}${layer}/${source}.webp`]
      if (!url) return null
      layers[layer][source] = url
    }
  }
  return { manifest, baseUrl, layers }
}

// Generated by tools/avatar/prepare_sprites.py; the folder is gitignored and may be empty.
const bundledManifests = import.meta.glob<unknown>('./assets/*/manifest.json', {
  eager: true,
  import: 'default',
})
const bundledImages = import.meta.glob<string>('./assets/*/**/*.webp', {
  eager: true,
  query: '?url',
  import: 'default',
})

export const bundledSpriteSets: ReadonlyMap<string, SpriteAssets> = buildSpriteSets(
  bundledManifests,
  bundledImages,
)
